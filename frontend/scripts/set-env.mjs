// Writes src/environments/environment.prod.ts from non-secret variables (process env or .env).
// Never put secrets here: the result is bundled into public JavaScript.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const fileVars = {};
const envFile = path.join(root, '.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) fileVars[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const get = (k, d) => process.env[k] ?? fileVars[k] ?? d;
const apiBaseUrl = get('API_BASE_URL', '/api').replace(/\/$/, '');
const siteUrl = get('SITE_URL', '').replace(/\/$/, '');

if (!/^(\/[A-Za-z0-9/_-]*|https:\/\/[^\s"'`]+)$/.test(apiBaseUrl)) {
  console.error(`API_BASE_URL must be a path like /api or an https:// URL (got "${apiBaseUrl}")`);
  process.exit(1);
}
if (siteUrl && !/^https?:\/\/[^\s"'`]+$/.test(siteUrl)) {
  console.error(`SITE_URL must be an http(s) URL (got "${siteUrl}")`);
  process.exit(1);
}

const out = `// Generated by scripts/set-env.mjs — do not edit by hand; contains NO secrets.
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  siteUrl: ${JSON.stringify(siteUrl)},
};
`;
fs.writeFileSync(path.join(root, 'src/environments/environment.prod.ts'), out);
console.log(`✓ environment.prod.ts written (apiBaseUrl=${apiBaseUrl}${siteUrl ? `, siteUrl=${siteUrl}` : ''})`);
